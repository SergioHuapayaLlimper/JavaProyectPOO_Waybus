    private void btnFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltrarActionPerformed
        String seleccion = cmbPopularidad.getSelectedItem().toString();

        DefaultTableModel modelo = (DefaultTableModel) TableRutas.getModel();
        TableRowSorter<DefaultTableModel> sorter = new TableRowSorter<>(modelo);
        TableRutas.setRowSorter(sorter);

        if (!seleccion.equals("Seleccione") && !seleccion.isEmpty()) {
            sorter.setRowFilter(RowFilter.regexFilter("^" + seleccion + "$", 2)); // Filtro exacto por Clasificación
        } else {
            sorter.setRowFilter(null); // Mostrar todos si no hay filtro
        }
    }//GEN-LAST:event_btnFiltrarActionPerformed

