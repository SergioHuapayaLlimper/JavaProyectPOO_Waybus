    private void cargarTablaRutas() {
        MantenimientoViajes mantenimiento = new MantenimientoViajes();
        Map<String, Integer> rutasContadas = mantenimiento.contarRutasDesdeArchivo("clientes.txt");
        Map<String, String> etiquetasGuardadas = cargarClasificacionesDesdeArchivo();

        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 2; // solo se edita la columna Clasificación
            }
        };

        modelo.addColumn("Ruta");
        modelo.addColumn("Cantidad");
        modelo.addColumn("Clasificación");

        for (Map.Entry<String, Integer> entry : rutasContadas.entrySet()) {
            String ruta = entry.getKey();
            int cantidad = entry.getValue();
            String clasificacion = etiquetasGuardadas.getOrDefault(ruta, "Seleccione");
            modelo.addRow(new Object[]{ruta, cantidad, clasificacion});
        }

        TableRutas.setModel(modelo);

        String[] opciones = {"Alta demanda", "Demanda media", "Baja demanda"};
        JComboBox<String> comboBox = new JComboBox<>(opciones);
        TableColumn colClasificacion = TableRutas.getColumnModel().getColumn(2);
        colClasificacion.setCellEditor(new DefaultCellEditor(comboBox));
    }
    
    private Map<String, String> cargarClasificacionesDesdeArchivo() {
        Map<String, String> clasificaciones = new HashMap<>();

        File archivo = new File("clasificaciones.txt");
        if (!archivo.exists()) return clasificaciones;

        try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
            String linea;
            while ((linea = br.readLine()) != null) {
                String[] partes = linea.split(",", 2);
                if (partes.length == 2) {
                    String ruta = partes[0].trim();
                    String clasificacion = partes[1].trim();
                    clasificaciones.put(ruta, clasificacion);
                }
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(null, "Error al cargar clasificaciones: " + e.getMessage());
        }

        return clasificaciones;
    }
    
    public FrmViajes() {
        initComponents();
        cmbPopularidad.addItem("Seleccione");
        cmbPopularidad.addItem("Alta demanda");
        cmbPopularidad.addItem("Demanda media");
        cmbPopularidad.addItem("Baja demanda");
        cargarTablaRutas(); // Aquí se carga automáticamente al abrir

        TableRutas.getModel().addTableModelListener(e -> {
            int fila = e.getFirstRow();
            int columna = e.getColumn();

            // Si cambió la columna "Clasificación"
            if (columna == 2) {
                String ruta = TableRutas.getValueAt(fila, 0).toString();
                String clasificacion = TableRutas.getValueAt(fila, 2).toString();

                if (!clasificacion.isEmpty()) {
                    MantenimientoViajes mv = new MantenimientoViajes();
                    mv.guardarClasificacion(ruta, clasificacion);
                }
            }
        });
    }

